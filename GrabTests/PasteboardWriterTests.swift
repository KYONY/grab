import AppKit
import Testing
@testable import Grab

@MainActor
struct PasteboardWriterTests {
    private func withWriter(_ body: (PasteboardWriter, NSPasteboard) -> Void) {
        let pasteboard = NSPasteboard(name: .init(UUID().uuidString))
        defer { pasteboard.releaseGlobally() }
        body(PasteboardWriter(pasteboard: pasteboard), pasteboard)
    }

    @Test func plainStringPresentAfterWrite() {
        withWriter { writer, pasteboard in
            writer.write("hello")
            #expect(pasteboard.string(forType: .string) == "hello")
        }
    }

    @Test func markerTypePresent() {
        withWriter { writer, pasteboard in
            writer.write("hello")
            #expect(pasteboard.types?.contains(NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")) == true)
        }
    }

    @Test func noRichTextType() {
        withWriter { writer, pasteboard in
            writer.write("hello")
            #expect(pasteboard.types?.contains(.rtf) != true)
        }
    }

    @Test func changeCountIncrementsAfterWrite() {
        withWriter { writer, _ in
            let before = writer.changeCount
            writer.write("hello")
            #expect(writer.changeCount > before)
        }
    }

    @Test func currentStringReturnsWrittenText() {
        withWriter { writer, _ in
            writer.write("hello")
            #expect(writer.currentString == "hello")
        }
    }
}
